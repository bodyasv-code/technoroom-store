import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {sitemapUrls,sitemapXml,SITE_ORIGIN} from '../api/sitemap.js';
const calls=[];
const tables={products:Array.from({length:1234},(_,i)=>({id:i+1,is_active:true})).concat({id:2000,is_active:false}),categories:[{id:1,slug:'office',is_active:true},{id:2,slug:'secret',is_active:false},{id:3,parent_id:2,slug:'hidden-child',is_active:true},{id:4,slug:'Проєктори & екрани',is_active:true}],articles:[{id:1,slug:'guide',is_published:true},{id:2,slug:'draft',is_published:false}]};
const client={from(table){let filter;return {select(){return this;},order(){return this;},eq(...args){filter=args;return this;},async range(start,end){calls.push({table,start,end});const rows=tables[table].filter(row=>!filter||row[filter[0]]===filter[1]);return {data:rows.slice(start,end+1),error:null};}};}};
const urls=await sitemapUrls(client);
assert.equal(urls.length,1243);
assert.ok(urls.includes(SITE_ORIGIN+'/contacts'));
assert.ok(urls.includes(SITE_ORIGIN+'/delivery'));
assert.ok(urls.includes(SITE_ORIGIN+'/returns'));
assert.ok(urls.includes(SITE_ORIGIN+'/product?id=1234'));
assert.ok(!urls.some(url=>/2000|secret|hidden-child|draft|vercel|\.html/.test(url)));
assert.ok(urls.includes(SITE_ORIGIN+'/catalog?category='+encodeURIComponent('Проєктори & екрани')));
assert.ok(calls.some(call=>call.table==='products'&&call.start===1000));
assert.match(sitemapXml(['https://example.test/?a=1&b=<x>']),/a=1&amp;b=&lt;x&gt;/);
assert.ok(!sitemapXml(urls).includes('<priority>'));
await assert.rejects(sitemapUrls({from(){return {select(){return this;},order(){return this;},eq(){return this;},async range(){return {data:null,error:{message:'secret'}};}};}}),/unavailable/);
const robots=await readFile(new URL('../public/robots.txt',import.meta.url),'utf8');
assert.ok(robots.includes('Sitemap: https://www.technoroom.com.ua/sitemap.xml'));
const config=JSON.parse(await readFile(new URL('../vercel.json',import.meta.url),'utf8'));
assert.ok(config.rewrites.some(rule=>rule.source==='/sitemap.xml'&&rule.destination==='/api/sitemap'));
await assert.rejects(readFile(new URL('../public/sitemap.xml',import.meta.url)),{code:'ENOENT'},'No static file may shadow the dynamic rewrite');
console.log('Sitemap: production clean URLs, >1000 active products, visible category hierarchy, published articles, XML escaping and fail-closed reads: PASS');
