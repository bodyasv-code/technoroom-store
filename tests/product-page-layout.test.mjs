import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {productSectionNavigation,productServiceSections,compactProductHeader,productSectionOffset,mountProductPageLayout} from '../public/product-page-layout.js';

assert.equal(compactProductHeader(180),false);
assert.equal(compactProductHeader(181),true);
assert.equal(compactProductHeader(81,true),true);
assert.equal(compactProductHeader(80,true),false);
assert.equal(productSectionOffset(64.2,56),141);
assert.equal(productSectionOffset(-10,0),20);
assert.match(productSectionNavigation(true),/href="#product-description"/);
assert.doesNotMatch(productSectionNavigation(false),/href="#product-description"/);
for(const id of ['product-specifications','product-delivery','product-warranty'])assert.ok(productSectionNavigation(false).includes('#'+id));
for(const id of ['product-delivery','product-warranty'])assert.ok(productServiceSections().includes('id="'+id+'"'));
for(const href of ['delivery.html','contacts.html','returns.html'])assert.ok(productServiceSections().includes('href="'+href+'"'));

// Real controller with a minimal DOM: no data or cart APIs are provided.
const classes=new Set(),styles=new Map(),listeners=new Map(),navListeners=new Map(),attributes=new Map();
let disconnected=0,scrollCall,focused=false;
const section={id:'product-specifications',getBoundingClientRect:()=>({top:500}),focus:()=>{focused=true;}};
const link={hash:'#product-specifications',setAttribute:(k,v)=>attributes.set(k,v),removeAttribute:k=>attributes.delete(k)};
const nav={querySelectorAll:()=>[link],getBoundingClientRect:()=>({height:56}),contains:x=>x===link,addEventListener:(k,v)=>navListeners.set(k,v),removeEventListener:k=>navListeners.delete(k)};
const body={classList:{add:k=>classes.add(k),contains:k=>classes.has(k),toggle:(k,on)=>on?classes.add(k):classes.delete(k)},style:{setProperty:(k,v)=>styles.set(k,v)}};
const doc={body,querySelector:()=>({getBoundingClientRect:()=>({height:classes.has('product-header-compact')?64:96})}),getElementById:id=>id===section.id?section:null};
const root={querySelector:()=>nav};
const win={scrollY:0,location:{hash:''},history:{pushState:(_a,_b,hash)=>{win.location.hash=hash;}},matchMedia:()=>({matches:true}),scrollTo:x=>{scrollCall=x;},requestAnimationFrame:()=>1,cancelAnimationFrame:()=>{},addEventListener:(k,v)=>listeners.set(k,v),removeEventListener:k=>listeners.delete(k),ResizeObserver:class{observe(){}disconnect(){disconnected++;}}};
const cleanup=mountProductPageLayout(root,{win,doc});
assert.equal(styles.get('--product-header-height'),'96px');
assert.equal(attributes.get('aria-current'),'location');
let prevented=false;
navListeners.get('click')({target:{closest:()=>link},button:0,ctrlKey:true,preventDefault:()=>{prevented=true;}});
assert.equal(prevented,false,'Modified clicks retain native browser behavior');
navListeners.get('click')({target:{closest:()=>link},button:0,preventDefault:()=>{prevented=true;}});
assert(prevented&&focused);
assert.equal(win.location.hash,'#product-specifications');
assert.deepEqual(scrollCall,{top:360,behavior:'instant'});
assert.equal(styles.get('--product-header-height'),'64px');
assert(classes.has('product-header-compact'));
const secondCleanup=mountProductPageLayout(root,{win,doc});
assert.equal(disconnected,1,'Gallery redraw disconnects the previous controller');
cleanup();
assert(listeners.has('scroll'),'An already disposed controller cannot remove the new one');
secondCleanup();
assert.equal(listeners.size,0);
assert.equal(navListeners.size,0);
assert.equal(disconnected,2);

const read=name=>readFile(new URL('../public/'+name,import.meta.url),'utf8');
const html=await read('product.html'),css=await read('product-page-layout.css'),app=await read('app.js');
assert.ok(html.indexOf('product-page-layout.css')>html.indexOf('product-modern.css'));
for(const name of ['index.html','catalog.html','checkout.html','admin.html'])assert.ok(!(await read(name)).includes('product-page-layout.css'));
assert.match(css,/product-content-grid \{ grid-template-columns: minmax\(0,1fr\)/);
assert.match(css,/overflow-x: auto/);
assert.match(css,/scroll-margin-top: var\(--product-section-offset/);
assert.match(css,/min-height: 44px/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
assert.equal(css.split('{').length,css.split('}').length);
assert.match(app,/productSectionNavigation\(hasDescription\)/);
assert.match(app,/mountProductPageLayout\(root\)/);
for(const id of ['product-description','product-specifications'])assert.ok(app.includes('id="'+id+'" tabindex="-1"'));
console.log('Product sections: conditional anchors, focus, header offsets, compact hysteresis, reduced motion, redraw cleanup and page isolation: PASS');
