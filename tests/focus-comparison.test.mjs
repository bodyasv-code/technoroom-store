import assert from 'node:assert/strict';
import {equivalentSpecification as equivalent} from '../public/specification-comparison.js';
import {createQualityAudit} from '../public/catalog-quality.js';
const option={projector:true};
for(const detail of ['ручне; f=15.843-17.445 мм','ручне; f=12.77 мм','ручне; f=11.9-15.5 мм'])assert.equal(equivalent('Фокусування','ручне',detail,option),true,detail);
assert.equal(equivalent('Фокусування','ручная','ручне; f=15.843-17.44 мм',option),true);
assert.equal(equivalent('Фокусування','manual focus','ручне; f=12.77 mm',option),true);
assert.equal(equivalent('Фокусування','ручне; f=12,77 мм','ручне; f=12.770 mm',option),true);
