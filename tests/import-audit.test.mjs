import assert from 'node:assert/strict';
import {createImportAudit,auditEligible,auditMarkup} from '../public/import-audit.js';
const row=(extra={})=>({key:'a',sku:'ABC-1',name:'Картридж Canon',hasPrice:true,price:500,specifications:{},...extra});
const metadata=(category='office-consumables-cartridges')=>({category,mapped:true});
const check=(value,products=[],meta=metadata(),rows=[value])=>createImportAudit(rows,products)(value,meta);
const codes=result=>result.issues.map(issue=>issue.code);
assert.equal(check(row()).blocked,false);
assert.equal(check(row()).issues.length,0);
assert.equal(check(row({sku:''})).blocked,true);
assert.equal(check(row({name:''})).blocked,true);
assert.equal(check(row(),[],{mapped:false}).blocked,true);
assert(codes(check(row({price:-1}))).includes('invalid-price'));
assert(codes(check(row({price:NaN}))).includes('invalid-price'));
assert(codes(check(row({hasStock:true,stock:-1}))).includes('invalid-stock'));
assert(codes(check(row({hasStock:true,stock:0}))).includes('invalid-stock')===false);
const noPrice=check(row({price:0}));
assert.equal(noPrice.blocked,false);
assert.equal(auditEligible(noPrice,new Set()),true);
assert(codes(noPrice).includes('no-price'));
assert(check(row({price:0}),[{id:1,sku:'ABC-1',price:900,category:'office-consumables-cartridges'}]).issues[0].message.includes('збережено'));
assert(codes(check(row(),[],metadata(),[row(),row({key:'b',sku:'abc-1'})])).includes('source-duplicate'));
assert(codes(check(row({priceDuplicate:true}))).includes('price-duplicate'));
assert(codes(check(row({contentDuplicate:true}))).includes('content-duplicate'));
assert(codes(check(row(),[{id:1,sku:'ABC-1'},{id:2,sku:'abc-1'}])).includes('catalog-duplicate'));
assert(codes(check(row(),[],metadata('office-printers'))).includes('consumable-category'));
assert(codes(check(row({name:'Термоетикетка 2E'}),[],metadata('office-printers'))).includes('supply-category'));
assert.equal(check(row({name:'Термоетикетка 2E'}),[],metadata('office-consumables-labels')).blocked,false);
assert(codes(check(row({name:'Комплект ресурсних матеріалів для сканера Ricoh'}),[],metadata('office-scanners'))).includes('supply-category'));
assert.equal(check(row({name:'Комплект ресурсних матеріалів для сканера Ricoh'}),[],metadata('office-accessories')).blocked,false);
assert(codes(check(row({name:'БФП Canon кольоровий'}),[],metadata('office-consumables-ink'))).includes('device-category'));
assert(codes(check(row({name:'БФП Canon кольоровий'}),[],metadata('office-scanners'))).includes('device-kind'));
assert(codes(check(row({name:'Принтер монохромний Canon',specifications:{'Тип друку':'Кольоровий'}}),[],metadata('office-printers-mono'))).includes('print-conflict'));
assert(codes(check(row({name:'Принтер Canon',subcategory:'Принтери кольорові'}),[],metadata('office-printers-mono'))).includes('print-conflict'));
assert.equal(check(row({name:'Картридж для кольорового принтера',specifications:{'Тип друку':'Монохромний'}})).blocked,false);
const review=check(row(),[{id:1,sku:'ABC-1',category:'office-printers'}]);
assert.equal(review.needsReview,true);
assert.equal(auditEligible(review,new Set()),false);
const reviewed=new Set([review.fingerprint]);
assert.equal(auditEligible(review,reviewed),true);
assert.equal(auditEligible(check(row({price:600}),[{id:1,sku:'ABC-1',category:'office-printers'}]),reviewed),false);
assert.equal(auditEligible(check(row({sku:''})),reviewed),false);
assert(codes(check(row({name:'Принтер Canon'}),[],metadata('office-printers'))).includes('unknown-print'));
assert(codes(check(row({name:'Принтер — невідома кольоровість'}),[],metadata('office-printers'))).includes('unknown-print'));
assert(codes(check(row({name:'Принтер Canon',specifications:{'Тип друку':'Кольоровий'}}),[{sku:'ABC-1',category:'office-printers-color',specifications:{'Тип друку':'Монохромний'}}],metadata('office-printers-color'))).includes('saved-print-conflict'));
assert(auditMarkup(check(row()),s=>s).includes('Перевірки пройдено'));
console.log('Import audit: checks passed');
