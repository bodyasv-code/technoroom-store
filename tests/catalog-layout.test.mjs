import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {mountCatalogLayout} from '../public/catalog-layout.js';
const read=file=>readFile(new URL('../public/'+file,import.meta.url),'utf8');
const html=await read('catalog.html'),css=await read('catalog-modern.css');
assert.match(html,/<details class="catalog-filter-panel" id="catalogFilterPanel" open>/);
assert.ok(html.indexOf('catalog-modern.css')>html.indexOf('store-modern.css'));
for(const id of ['brandFilter','priceMin','priceFilter','stockFilter','screenSpecificationFilters','catalogSort','catalogPageSize','activeCatalogFilters','catalogGrid'])assert.equal(html.split('id="'+id+'"').length,2);
for(const page of ['index.html','product.html','admin.html','checkout.html'])assert.ok(!(await read(page)).includes('catalog-modern.css'));
const handlers={},mediaHandlers={};let focused=0,scrolled=0;
const panel={open:true,addEventListener:(key,fn)=>handlers[key]=fn,querySelector:()=>({focus:()=>focused++}),scrollIntoView:()=>scrolled++};
const done={hidden:true,addEventListener:(key,fn)=>handlers['done:'+key]=fn};
const doc={getElementById:id=>id==='catalogFilterPanel'?panel:done};
const media={matches:true,addEventListener:(key,fn)=>mediaHandlers[key]=fn};
mountCatalogLayout(doc,media);
assert.equal(panel.open,false);assert.equal(done.hidden,false);
panel.open=true;handlers['done:click']();
assert.equal(panel.open,false);assert.equal(focused,1);assert.equal(scrolled,1);
media.matches=false;mediaHandlers.change();
assert.equal(panel.open,true);assert.equal(done.hidden,true);
panel.open=false;handlers.toggle();assert.equal(panel.open,true);
handlers['done:click']();assert.equal(panel.open,true);
media.matches=true;mediaHandlers.change();assert.equal(panel.open,false);
assert.match(css,/@media\(max-width:900px\)/);
assert.match(css,/min-height: 48px/);
assert.match(css,/minmax\(0,1fr\)/);
assert.equal((css.match(/{/g)||[]).length,(css.match(/}/g)||[]).length);
console.log('Category layout: responsive native filter disclosure, keyboard focus, resize, unchanged field IDs and page isolation: PASS (visual QA pending)');
