import assert from 'node:assert/strict';
import {planOfficeSpecificationCleanup as plan} from '../scripts/office-specification-cleanup.mjs';
const p={id:4331,category:'office-mfp-color',specifications:{https:'//example.com/doc','ОС':'Windows 11 Інтерфейс: USB 2.0','Інтерфейс':'USB 2.0','Принтер (швидкість':'до 25 стор/хв ч/б/колір (A4)',"пам’ять":'до 512 стор','масштабування':'25-400%)'}};
const snapshot=JSON.stringify(p),result=plan(p);
assert.equal(result.after['Документ постачальника'],'https://example.com/doc');
assert.equal(result.after['ОС'],'Windows 11');
assert.equal(result.after['Інтерфейс'],'USB 2.0');
assert.equal(result.after['Швидкість друку'],p.specifications['Принтер (швидкість']);
assert.equal(plan({specifications:{'Принтер (швидкість':'25 (A4'}}).changes.length,0,'Unbalanced value not repaired');
assert.equal(result.after['Масштабування копіювання'],'25-400%');
assert.equal(result.after['пам’ять'],'до 512 стор');
assert.equal(JSON.stringify(p),snapshot);
assert.equal(plan({...p,specifications:result.after}).changes.length,0,'Idempotent');
assert.equal(plan({category:'office-printers-color',specifications:{'Принтер (швидкість':'до 25 стор/хв'}}).after['Швидкість друку'],'до 25 стор/хв');
assert.equal(plan({category:'projectors',specifications:{'масштабування':'25-400%)'}}).changes.length,0,'Printer rules never apply to projectors');
assert.deepEqual(plan({specifications:{'ОС':'Windows Інтерфейс: USB','Інтерфейс':'Ethernet'}}).changes,[],'Never remove conflicts');
assert.deepEqual(plan({specifications:{'https':'//example.com/a','Документ постачальника':'https://other.example/b'}}).changes,[]);
assert.deepEqual(plan({specifications:{https:'//user:secret@example.com/a'}}).changes,[]);
console.log('Office repair: exact duplicate tails, explicit labels, URL preservation, ambiguity and conflict guards, immutability, idempotence: PASS');
