assert.equal(equivalent('Фокусування','моторизоване','автоматичне',option),false);
assert.equal(equivalent('Фокусування','ручне; f=12.77 мм','ручне; f=15.843 мм',option),false);
assert.equal(equivalent('Фокусування','ручне','ручне; невідомі параметри',option),false);
assert.equal(equivalent('Фокусування','ручне','ручне; f=12.77 мм'),false);
