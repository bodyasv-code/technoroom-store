import assert from 'node:assert/strict';
import {equivalentSpecification as equivalent} from '../public/specification-comparison.js';
import {isSpecializedPrinterName} from '../public/product-identity.js';
import {createQualityAudit} from '../public/catalog-quality.js';
const option={projector:true};
assert.equal(equivalent('Джерело світла','Світлодіод','LED, 20000',option),true);
assert.equal(equivalent('Джерело світла','Світлодіод','WLED, 30000',option),true);
assert.equal(equivalent('Джерело світла','Лазер','Laser, 20000/30000',option),true);
assert.equal(equivalent('Джерело світла','Лампа','UHP 210W, 6000/12000',option),true);
assert.equal(equivalent('Джерело світла','Світлодіод','LED+LASER, 20000/30000',option),false);
assert.equal(equivalent('Джерело світла','LED, 20000','LED, 30000',option),false);
assert.equal(equivalent('Джерело світла','LED','Лазер',option),false);
assert.equal(equivalent('Роздільна здатність','Full HD','1920x1080 (FHD)',option),true);
assert.equal(equivalent('Роздільна здатність','Full HD','3840 × 2160',option),false);
assert.equal(equivalent('Контраст','1000:1','2000:1',option),false);
for(const name of ['Принтер етикеток ink color Epson TM-C3500','Принтер Epson ColorWorks C6000Ae','Printer thermal Zebra','Printer label Epson'])assert.equal(isSpecializedPrinterName(name),true,name);
for(const name of ['Термоетикетка 2E','Картридж для принтера етикеток','Принтер Epson EcoTank L3250','Проєктор Epson'])assert.equal(isSpecializedPrinterName(name),false,name);
const sample={id:1,name:'Проєктор AOpen',category:'projectors',brand:'AOpen',price:100,image_path:'photo.jpg',specifications:{'Джерело світла':'Світлодіод','Джерело світла (тип, термін роботи):':'WLED, 30000'}};
const before=JSON.stringify(sample);
const result=createQualityAudit([sample],[{slug:'projectors',name:'Проєктори'}]);
assert.equal(result[0].issues.some(issue=>issue.code==='conflict'),false);
assert.equal(JSON.stringify(sample),before);
const threeValues={...sample,specifications:{'Джерело світла':'Світлодіод','Джерело світла (тип, термін роботи):':'LED, 20000','Джерело світла (інше значення 2)':'LED, 30000'}};
assert.equal(createQualityAudit([threeValues],[{slug:'projectors'}])[0].issues.some(issue=>issue.code==='conflict'),true);
console.log('Specification equivalence and specialized printer safeguards: checks passed');
