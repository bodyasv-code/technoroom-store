import assert from 'node:assert/strict';
import {printerDisplayEntries,isPrinterDevice} from '../public/printer-display.js';
const source = [['дозвіл','1200х2400 т/д'],['Windows','11/10/8.1 Mac: macOS 13 Chrome OS'],['max кількість копій','99 ) Сканер (швидкість: кольорове: 3,5 мс/лінію (300 точок на дюйм)'],['Документ','Планшет: A4/Letter (216 x 297 мм), АПД: A4/Letter/Legal (216 x 356 мм) Дуплекс: так, звичайний папір']];
const before = JSON.stringify(source);
const result = printerDisplayEntries(source);
assert.equal(result[0][0],'Роздільна здатність');
assert.ok(result.some(([k,v])=>k==='Швидкість сканування'&&v==='кольорове: 3,5 мс/лінію (300 точок на дюйм)'));
assert.ok(result.some(([k,v])=>k==='Дуплекс'&&v==='Так, звичайний папір'));
assert.ok(result.some(([k,v])=>k==='Формат сканування (планшет)'&&v==='A4/Letter (216 x 297 мм)'));
assert.ok(result.some(([k,v])=>k==='Операційні системи'&&v==='Windows, macOS, Chrome OS'));
assert.equal(JSON.stringify(source),before);
assert.ok(!printerDisplayEntries([['Опис','Дуплекс: опціональний']]).some(([k])=>k==='Дуплекс'));
assert.equal(isPrinterDevice({name:'Картридж до HP MFP',category:'office-mfp'}),false);
assert.equal(isPrinterDevice({name:'БФП Canon'}),true);
assert.deepEqual(printerDisplayEntries(result),result);
console.log('Printer presentation safeguards: OK');
const connections = printerDisplayEntries([['Інтерфейси','Wi‑Fi'],['Мережа','Ethernet: 10/100 Мбіт/с'],['Мобільні системи','iOS Інтерфейс: Hi-Speed USB (порт B)']]);
assert.deepEqual(connections[0],['Інтерфейси','Wi-Fi, Ethernet, USB']);
assert.deepEqual(printerDisplayEntries(connections),connections);
assert.equal(printerDisplayEntries([['Інтерфейси','Wi-Fi'],['Мережа','optional Ethernet: 10/100']])[0][1],'Wi-Fi');
assert.deepEqual(printerDisplayEntries([['Друк','швидкість ч/б-38 стор/хв, цв-24 стор/хв']])[0],['Швидкість друку','ч/б-38 стор/хв, цв-24 стор/хв']);
assert.deepEqual(printerDisplayEntries([['Принтер (швидкість друку','колір: 33 стор/хв, ч/б: 33 стор/хв']])[0],['Швидкість друку','колір: 33 стор/хв, ч/б: 33 стор/хв']);
assert.ok(printerDisplayEntries([['Принтер (швидкість друку ч/б 18стор/хв, кол.','4 стор/хв']])[0][1].includes('18стор/хв, кол.: 4 стор/хв'));
assert.ok(printerDisplayEntries([['Тип пристрою','БФП']], 'Кольоровий лазерний БФП А4 (принтер, копір)').some(([k,v])=>k==='Формат'&&v==='A4'));
assert.ok(printerDisplayEntries([['Принтер, сканер, копіювання, факс. Формат','А3+']]).some(([k,v])=>k==='Формат'&&v==='A3+'));
assert.ok(!printerDisplayEntries([['Сканування','Формат A4']], 'Сканування: A4').some(([k])=>k==='Формат'));
assert.ok(printerDisplayEntries([['Формат','A3']], 'БФП A3+').some(([k,v])=>k==='Формат'&&v==='A3'));
