import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {printerDuplexMode as mode, printerDuplexFilterValues as values, writePrinterDuplex} from '../public/printer-duplex.js';
import {printerFormatFilterValues as formats} from '../public/printer-format-filter.js';
import {printerDisplayEntries} from '../public/printer-display.js';
import {readCatalogFilterState} from '../public/catalog-filter-state.js';
const entries=value=>[['Дуплекс',value]];
for(const value of ['Є','Так','стандартно','Автоматичний']) assert.equal(mode(entries(value)),'automatic');
for(const value of ['Ручний','Вручну','Ручний (через драйвер)','manual duplex']) assert.equal(mode(entries(value)),'manual');
assert.equal(mode(entries('Не підтримується')),'unsupported');
assert.equal(mode([['Автоматичний двосторонній друк','Не підтримується']]),'unknown');
assert.equal(mode(entries('Не підтримується автоматичний друк')),'unknown');
for(const value of ['Ні','Немає','Не вказано']) assert.equal(mode(entries(value)),'unknown');
assert.equal(mode(entries('опціонально')),'optional');
assert.equal(mode([['Дуплексний друк','Немає'],['Дуплекс','Ручний']]),'manual');
assert.equal(mode([['Дуплексний друк','Є'],['Дуплекс','Ручний']]),'conflict');
assert.equal(mode([['Дуплексний друк','Є'],['Дуплекс','Немає']]),'conflict');
assert.equal(mode([['Дуплекс','Ручний'],['Двосторонній друк','Не підтримується']]),'conflict');
assert.equal(mode([], 'Ручний двосторонній друк'),'manual');
assert.equal(mode([], 'Дуплекс: Автоматичний'),'automatic');
assert.equal(mode(entries('Ручний'),'Дуплекс: так'),'manual');
assert.deepEqual(values({specifications:{'Дуплекс':'Ручний'}}),['Ручний']);
assert.deepEqual(values({specifications:{'Дуплекс':'Не підтримується'}}),['Не підтримується']);
for(const value of ['Немає','Не вказано','опціонально']) assert.deepEqual(values({specifications:{'Дуплекс':value}}),[]);
assert.deepEqual(values({specifications:{'Дуплекс':'Є','Двосторонній друк':'Ручний'}}),[]);
const original={'Дуплекс:':'Є','Дуплексний друк':'Немає','Інтерфейси':['USB']};
assert.deepEqual(writePrinterDuplex(original,'manual'),{'Двосторонній друк':'Ручний','Інтерфейси':['USB']});
assert.deepEqual(writePrinterDuplex(original,''),{'Інтерфейси':['USB']});
assert.equal(original['Дуплекс:'],'Є');
assert.deepEqual(printerDisplayEntries([['Дуплексний друк','Немає'],['Дуплекс','Ручний (через драйвер)']]),[['Двосторонній друк','Ручний']]);
assert.deepEqual(printerDisplayEntries([['Двосторонній друк','Ручний'],['Деталі','Дуплекс: так']]),[['Деталі','Дуплекс: так'],['Двосторонній друк','Ручний']]);
for(const value of ['A3','А3+','A3/A3+','БФП A3+']) assert.deepEqual(formats(value),['A3']);
assert.deepEqual(formats('A3+ A4'),['A3','A4']);
assert.deepEqual(formats('A30 A43'),[]);
const params=new URLSearchParams({specs:JSON.stringify([['printer-format',['A3','A3+','A3/A3+']],['printer-duplex',['Є']]])});
assert.deepEqual(readCatalogFilterState(params).specs,[['printer-format',['A3']],['printer-duplex',['Автоматичний']]]);
const admin=readFileSync(new URL('../public/admin.js',import.meta.url),'utf8');
assert.match(admin,/if\(duplexControl.dataset.changed==='true'\)specifications=writePrinterDuplex/);
assert.match(admin,/<option value="">— Не вказано —<\/option><option value="automatic">Автоматичний/);
console.log('Duplex modes, conservative legacy support, format grouping: OK');
