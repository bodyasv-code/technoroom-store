import assert from 'node:assert/strict';
import {verifiedDuplexRepair,applyVerifiedDuplexRepair,verifiedDuplexProducts} from '../public/verified-duplex-repair.js';
assert.equal(verifiedDuplexProducts.length,9);
const product={id:4530,sku:'4ZB96A',price:123,brand:'HP',specifications:{'Дуплекс':'немає','Дуплексний друк':'Є','Вхід':['USB','Ethernet'],'Роздільна здатність':'600:600'}};
const before=JSON.stringify(product);
const plan=verifiedDuplexRepair(product);
assert.equal(plan.specifications['Дуплексний друк'],'Немає');
assert.equal(plan.specifications['Дуплекс'],'Ручний (через драйвер)');
assert.deepEqual(plan.specifications['Вхід'],['USB','Ethernet']);
assert.equal(JSON.stringify(product),before);
assert.equal(verifiedDuplexRepair({...product,specifications:plan.specifications}),null);
assert.equal(verifiedDuplexRepair({...product,sku:'4ZB97A'}),null);
assert.equal(verifiedDuplexRepair({...product,id:999}),null);
const calls=[];
const chain={update(value){calls.push(['update',value]);return this},eq(...args){calls.push(['eq',...args]);return this},async select(){return {data:[{id:4530}]}}};
assert.equal(await applyVerifiedDuplexRepair({from(){return chain}},plan),4530);
assert.deepEqual(Object.keys(calls[0][1]),['specifications']);
assert.deepEqual(calls.slice(1).map(call=>call[1]),['id','sku','specifications']);
await assert.rejects(applyVerifiedDuplexRepair({from(){return {...chain,async select(){return {data:[]}}}}},plan));
console.log('Verified nine-product repair scope: OK');
