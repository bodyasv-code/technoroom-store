import assert from 'node:assert/strict';
import {projectorResolutionLabel,normalizeProjectorResolution,projectorResolutionFilterValue,compareProjectorResolutions,projectorResolutionStandards} from '../public/projector-specs.js';
for(const raw of ['Full HD','FULL HD','FHD','1920x1080'])assert.equal(projectorResolutionLabel(raw),'FULL HD (1920 × 1080)');
for(const raw of ['WUXGA','1920 x 1200'])assert.equal(projectorResolutionLabel(raw),'WUXGA (1920 × 1200)');
assert.equal(projectorResolutionLabel('1980 x 1200'),'1980 x 1200');
assert.equal(projectorResolutionLabel('WXGA'),'WXGA (1280 × 800)');
assert.equal(projectorResolutionLabel('HD'),'HD (1280 × 720)');
assert.equal(projectorResolutionLabel('4k uhd'),'4K UHD (3840 × 2160)');
assert.equal(projectorResolutionFilterValue('1280x800'),'WXGA');
assert.equal(projectorResolutionFilterValue('1280x720'),'HD');
assert.equal(projectorResolutionFilterValue('4096x2160'),'4096 × 2160');
assert.equal(projectorResolutionFilterValue('неправильний опис зуму'),'');
assert.equal(new Set(['Full HD','FHD','1920x1080'].map(projectorResolutionFilterValue)).size,1);
assert.equal(new Set(['4K UHD','4k','3840x2160'].map(projectorResolutionFilterValue)).size,1);
assert.deepEqual(['4K UHD','WUXGA','HD','WXGA','Full HD'].sort(compareProjectorResolutions),['HD','WXGA','Full HD','WUXGA','4K UHD']);
assert.equal(new Set(projectorResolutionStandards.map(projectorResolutionLabel)).size,projectorResolutionStandards.length);
assert.equal(normalizeProjectorResolution('Full HD'),'Full HD');
assert.equal(normalizeProjectorResolution('WUXGA'),'WUXGA');
console.log('Resolution display labels: checks passed');
