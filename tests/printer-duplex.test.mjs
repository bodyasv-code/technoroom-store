import assert from 'node:assert/strict';
import {printerDuplexState as state} from '../public/printer-duplex.js';
import {createQualityAudit} from '../public/catalog-quality.js';
assert.equal(state([['Дуплекс','немає']]),'no');
assert.equal(state([['Дуплекс','ні']]),'no');
assert.equal(state([['Дуплекс','Вручну']]),'no');
assert.equal(state([['Дуплекс','опціонально']]),'optional');
assert.equal(state([['Дуплекс','стандартно']]),'yes');
assert.equal(state([['Дуплекс','немає'],['Дуплексний друк','Є']]),'conflict');
assert.notEqual(state([], 'Принтер Duplex USB; Дуплекс: немає'),'yes');
assert.notEqual(state([], 'Дуплекс: ручний'),'yes');
assert.notEqual(state([], 'Дуплекс: опціонально'),'yes');
assert.equal(state([], 'Принтер A4 Duplex USB'),'yes');
assert.equal(state([], 'Принтер USB'),'unknown');
const specs={'Дуплекс':'немає','Дуплексний друк':'Є'};
const audit=createQualityAudit([{id:1,name:'Принтер HP',category:'office-printers',brand:'HP',price:1,image_path:'x',specifications:specs}],[{slug:'office-printers',name:'Принтери'}]);
assert.ok(audit[0].issues.some(issue=>issue.code==='conflict'&&issue.detail.includes('Дуплекс')));
assert.deepEqual(specs,{'Дуплекс':'немає','Дуплексний друк':'Є'});
console.log('Duplex negative/conflict safeguards: OK');
const formatAudit=createQualityAudit([{id:2,name:'БФП Epson',category:'office-printers',brand:'Epson',price:1,image_path:'x',specifications:{'Формат':'A3','Принтер, сканер, копір. Формат':'А3+'}}],[{slug:'office-printers',name:'Принтери'}]);
assert.ok(formatAudit[0].issues.some(issue=>issue.code==='conflict'&&issue.detail.includes('A3+')));
